logger = logging.getLogger("AgentFactory")


class AgentSpecification(BaseModel):
    agent_id: str = Field(description="Unique snake_case identifier")
    name: str = Field(description="Human-readable title")
    class_name: str = Field(description="PascalCase class name")
    role: str = Field(description="Description of specialized role")
    description: str = Field(description="Purpose and operational context")
    task_type: str = Field(description="Classification of primary task handled")
    allowed_permissions: List[Permission] = Field(default_factory=list)
    tools: List[str] = Field(default_factory=list)
    logic_summary: str = Field(default="Custom analytics processing logic")


class AgentFactorySecurityError(Exception):
    """Raised when generated agent code breaches security or sandbox rules."""
    pass


class ASTSecurityAuditor(ast.NodeVisitor):
    """
    Static code analyzer inspecting Python AST to block dangerous imports and constructs.
    """

    FORBIDDEN_IMPORTS = {
        "os", "sys", "subprocess", "shutil", "ctypes", "socket",
        "importlib", "pickle", "shelve", "pty", "commands"
    }

    FORBIDDEN_CALLS = {
        "eval", "exec", "globals", "locals", "__import__", "compile", "open"
    }

    def __init__(self):
        self.violations: List[str] = []

    def visit_Import(self, node: ast.Import):
        for alias in node.names:
            base_mod = alias.name.split(".")[0]
            if base_mod in self.FORBIDDEN_IMPORTS:
                self.violations.append(f"Forbidden import '{alias.name}' detected at line {node.lineno}")
        self.generic_visit(node)

    def visit_ImportFrom(self, node: ast.ImportFrom):
        if node.module:
            base_mod = node.module.split(".")[0]
            if base_mod in self.FORBIDDEN_IMPORTS:
                self.violations.append(f"Forbidden import from '{node.module}' detected at line {node.lineno}")
        self.generic_visit(node)

    def visit_Call(self, node: ast.Call):
        if isinstance(node.func, ast.Name):
            if node.func.id in self.FORBIDDEN_CALLS:
                self.violations.append(f"Dangerous function call '{node.func.id}()' at line {node.lineno}")
        self.generic_visit(node)

    def visit_Attribute(self, node: ast.Attribute):
        if node.attr in ["__subclasses__", "__globals__", "__code__", "__dict__"]:
            self.violations.append(f"Attempted reflection exploit via attribute '{node.attr}' at line {node.lineno}")
        self.generic_visit(node)


class AgentFactory:
    """
    Generates, audits, tests, registers, and tracks new modular agent plugins.
    """

    def __init__(self, output_dir: str = "dynamic_agents", tests_dir: str = "tests/dynamic", docs_dir: str = "docs/agents"):
        self.output_dir = output_dir
        self.tests_dir = tests_dir
        self.docs_dir = docs_dir
        self.generation_history: List[Dict[str, Any]] = []

        os.makedirs(self.output_dir, exist_ok=True)
        os.makedirs(self.tests_dir, exist_ok=True)
        os.makedirs(self.docs_dir, exist_ok=True)

    def validate_permissions_request(self, requested_permissions: List[Permission]):
        """Ensures that dynamic agents cannot request sensitive or financial permissions."""
        req_set = set(requested_permissions)
        forbidden = req_set - DYNAMIC_AGENT_ALLOWED_PERMISSIONS
        if forbidden:
            raise PermissionDeniedError(
                f"Dynamic agent cannot be granted privileged permissions: {[p.value for p in forbidden]}. "
                f"Allowed dynamic permissions: {[p.value for p in DYNAMIC_AGENT_ALLOWED_PERMISSIONS]}"
            )

    def generate_agent_code(self, spec: AgentSpecification) -> str:
        """Constructs Python source code for the new agent."""
        perms_code = ", ".join([f"Permission.{p.name}" for p in spec.allowed_permissions])
        tools_code = repr(spec.tools)

        code = f'''"""
Dynamic Agent Module: {spec.name}
Role: {spec.role}
Generated by AgentFactory at {datetime.now(timezone.utc).isoformat()}
"""

from typing import Dict, Any
import logging
from agents.base import BaseAgent
from core.permissions import Permission

logger = logging.getLogger("{spec.class_name}")


class {spec.class_name}(BaseAgent[Dict[str, Any], Dict[str, Any]]):
    """
    {spec.description}
    """

    def __init__(self, agent_id: str = "{spec.agent_id}"):
        super().__init__(
            agent_id=agent_id,
            name="{spec.name}",
            role="{spec.role}",
            allowed_permissions={{{perms_code}}},
            tools={tools_code},
            is_dynamic=True
        )

    async def _run_task(self, input_data: Dict[str, Any]) -> Dict[str, Any]:
        logger.info("Executing {spec.class_name} with task: {spec.task_type}")
        
        # Primary operational logic: {spec.logic_summary}
        result = {{
            "status": "COMPLETED",
            "agent_id": self.agent_id,
            "task_type": "{spec.task_type}",
            "processed_input_keys": list(input_data.keys()),
            "analysis_result": f"Successfully evaluated {{len(input_data)}} input metrics."
        }}
        return result
'''
        return code

    def generate_test_code(self, spec: AgentSpecification) -> str:
        """Generates unit tests for the dynamic agent."""
        agent_file_path = os.path.abspath(os.path.join(self.output_dir, f"{spec.agent_id}.py"))
        test_code = f'''"""
Unit Tests for dynamic agent: {spec.class_name}
"""

import sys
import os
import pytest
import importlib.util

spec_path = r"{agent_file_path}"
mod_spec = importlib.util.spec_from_file_location("{spec.agent_id}", spec_path)
mod = importlib.util.module_from_spec(mod_spec)
mod_spec.loader.exec_module(mod)
AgentClass = getattr(mod, "{spec.class_name}")
AgentClass.__test__ = False

from models.messages import AgentMessage, TaskStatus
from core.permissions import Permission
from database.db import init_db


@pytest.mark.asyncio
async def test_{spec.agent_id}_execution():
    await init_db()
    agent = AgentClass()
    assert agent.agent_id == "{spec.agent_id}"
    assert agent.is_dynamic is True

    msg = AgentMessage(
        agent_id=agent.agent_id,
        task_type="{spec.task_type}",
        input_data={{"metric_a": 100, "metric_b": 250}}
    )

    result_msg = await agent.execute(msg)
    assert result_msg.status == TaskStatus.SUCCESS
    assert result_msg.output_data is not None
    assert result_msg.output_data["status"] == "COMPLETED"
'''
        return test_code

    def generate_documentation(self, spec: AgentSpecification) -> str:
        """Generates markdown documentation for the dynamic agent."""
        doc = f"""# Agent Specification: {spec.name}

- **Agent ID:** `{spec.agent_id}`
- **Class Name:** `{spec.class_name}`
- **Role:** {spec.role}
- **Task Type:** `{spec.task_type}`
- **Dynamic:** Yes (Generated via `AgentFactory`)

## Description
{spec.description}

## Assigned Permissions
{', '.join([f'`{p.value}`' for p in spec.allowed_permissions])}

## Tools
{', '.join([f'`{t}`' for t in spec.tools])}

## Logic
{spec.logic_summary}
"""
        return doc

    async def build_and_register_agent(self, spec: AgentSpecification) -> Dict[str, Any]:
        """
        Orchestrates full creation workflow:
        1. Validates requested permissions
        2. Generates code, tests, docs
        3. Runs AST static security audit
        4. Writes files to disk
        5. Executes QA tests in sandbox
        6. Registers agent with rollback support
        """
        logger.info("AgentFactory: Initiating creation of '%s' (%s)", spec.name, spec.agent_id)

        # 1. Permission check
        self.validate_permissions_request(spec.allowed_permissions)

        # 2. Code generation
        agent_code = self.generate_agent_code(spec)
        test_code = self.generate_test_code(spec)
        doc_code = self.generate_documentation(spec)

        # 3. Static AST Security Audit
        try:
            tree = ast.parse(agent_code)
            auditor = ASTSecurityAuditor()
            auditor.visit(tree)
            if auditor.violations:
                raise AgentFactorySecurityError(f"Static security audit failed: {'; '.join(auditor.violations)}")
        except SyntaxError as se:
            raise AgentFactorySecurityError(f"Generated code has syntax error: {se}")

        # 4. Write files
        agent_file = os.path.join(self.output_dir, f"{spec.agent_id}.py")
        test_file = os.path.join(self.tests_dir, f"test_{spec.agent_id}.py")
        doc_file = os.path.join(self.docs_dir, f"{spec.agent_id}.md")

        with open(agent_file, "w", encoding="utf-8") as f:
            f.write(agent_code)
        with open(test_file, "w", encoding="utf-8") as f:
            f.write(test_code)
        with open(doc_file, "w", encoding="utf-8") as f:
            f.write(doc_code)

        # 5. Isolated QA Verification
        qa_agent: Optional[QAAgent] = agent_registry.get("qa_agent")
        if qa_agent:
            qa_msg = await qa_agent.execute(AgentMessage(
                agent_id=qa_agent.agent_id,
                task_type="VERIFY_DYNAMIC_AGENT",
                input_data={"target": spec.agent_id, "test_path": test_file}
            ))
            qa_report = qa_msg.output_data or {}
            if not qa_report.get("is_system_ready", False):
                # Rollback on test failure
                self.rollback_agent(spec.agent_id)
                raise AgentFactorySecurityError(
                    f"Agent failed isolated unit tests: {qa_report.get('failures', [])}"
                )

        # 6. Dynamic Import and Registration
        try:
            mod_spec = importlib.util.spec_from_file_location(f"dynamic_agents.{spec.agent_id}", agent_file)
            mod = importlib.util.module_from_spec(mod_spec)
            mod_spec.loader.exec_module(mod)
            agent_class = getattr(mod, spec.class_name)
            agent_instance = agent_class()

            agent_registry.register(agent_instance)
        except Exception as exc:
            self.rollback_agent(spec.agent_id)
            raise AgentFactorySecurityError(f"Failed to import/instantiate dynamic agent: {exc}")

        # Record history
        record = {
            "agent_id": spec.agent_id,
            "created_at": datetime.now(timezone.utc).isoformat(),
            "status": "ACTIVE",
            "files": [agent_file, test_file, doc_file]
        }
        self.generation_history.append(record)

        logger.info("AgentFactory: Agent '%s' verified and registered successfully!", spec.agent_id)
        return {
            "status": "SUCCESS",
            "agent_id": spec.agent_id,
            "files": record["files"],
            "message": f"Agent {spec.name} successfully created, tested, and registered."
        }

    def rollback_agent(self, agent_id: str) -> None:
        """Removes generated files and unregisters agent."""
        logger.warning("AgentFactory: Rolling back dynamic agent '%s'", agent_id)
        agent_registry.unregister(agent_id)

        for p in [
            os.path.join(self.output_dir, f"{agent_id}.py"),
            os.path.join(self.tests_dir, f"test_{agent_id}.py"),
            os.path.join(self.docs_dir, f"{agent_id}.md")
        ]:
            if os.path.exists(p):
                try:
                    os.remove(p)
                except Exception as e:
                    logger.error("Failed removing %s during rollback: %s", p, e)


# Global AgentFactory instance
agent_factory = AgentFactory()
