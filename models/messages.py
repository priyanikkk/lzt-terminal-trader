"""
Typed message contracts for inter-agent communication and task execution.
"""

from enum import Enum
from typing import TypeVar, Generic, Optional, List, Dict, Any
from datetime import datetime, timezone
import uuid
from pydantic import BaseModel, Field


class TaskStatus(str, Enum):
    PENDING = "PENDING"
    RUNNING = "RUNNING"
    SUCCESS = "SUCCESS"
    FAILED = "FAILED"
    BLOCKED = "BLOCKED"
    SKIPPED = "SKIPPED"


TInput = TypeVar("TInput")
TOutput = TypeVar("TOutput")


class AgentMessage(BaseModel, Generic[TInput, TOutput]):
    """
    Standard message envelope exchanged between agents and the orchestrator.
    """
    task_id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    agent_id: str = Field(description="ID of the processing or producing agent")
    task_type: str = Field(description="Classification of the task, e.g. SCAN, INSPECT, PRICE")
    status: TaskStatus = Field(default=TaskStatus.PENDING)
    input_data: TInput = Field(description="Input payload provided to the agent")
    output_data: Optional[TOutput] = Field(default=None, description="Result generated by the agent upon success")
    errors: List[str] = Field(default_factory=list, description="List of error messages if task failed")
    created_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
    completed_at: Optional[datetime] = Field(default=None)
    metadata: Dict[str, Any] = Field(default_factory=dict)

    def mark_running(self) -> None:
        self.status = TaskStatus.RUNNING

    def mark_success(self, output: TOutput) -> None:
        self.status = TaskStatus.SUCCESS
        self.output_data = output
        self.completed_at = datetime.now(timezone.utc)

    def mark_failed(self, error_message: str) -> None:
        self.status = TaskStatus.FAILED
        self.errors.append(error_message)
        self.completed_at = datetime.now(timezone.utc)

    def mark_blocked(self, reason: str) -> None:
        self.status = TaskStatus.BLOCKED
        self.errors.append(reason)
        self.completed_at = datetime.now(timezone.utc)
